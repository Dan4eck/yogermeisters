export function localizeRetreat(retreat: Retreat, language: Language): Retreat {
  const localized = retreatTranslationById[language]?.[retreat.id];

  if (!localized) {
    return retreat;
  }

  const localizedPostBlocks = retreat.postBlocks.map((block) => {
    const translatedBlock = localized.postBlocks[block.id];
    if (!translatedBlock) {
      return block;
    }

    if (block.type === 'paragraph' && typeof translatedBlock.text === 'string') {
      return { ...block, text: translatedBlock.text };
    }

    if (block.type === 'image' && typeof translatedBlock.alt === 'string') {
      return { ...block, alt: translatedBlock.alt };
    }

    return block;
  });

  return {
    ...retreat,
    title: localized.title,
    location: localized.location,
    dateLabel: localized.dateLabel ?? retreat.dateLabel,
    postBlocks: localizedPostBlocks,
  };
}
