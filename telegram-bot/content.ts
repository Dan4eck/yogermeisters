export function createMeditationFunnelPlan(meditationAudio: string): TelegramFunnelPlan {
  return {
    key: MEDITATION_FUNNEL_KEY,
    version: MEDITATION_FUNNEL_VERSION,
    steps: [
      {
        contentKey: MEDITATION_CONTENT_KEY,
        delayMs: 0,
        content: {
          type: 'audio',
          audio: meditationAudio,
          caption: MEDITATION_AUDIO_CAPTION,
          title: MEDITATION_AUDIO_TITLE,
        },
      },
      {
        contentKey: FOLLOW_UP_CONTENT_KEY,
        delayMs: 30 * MINUTE_MS,
        content: { type: 'text', text: FOLLOW_UP_MESSAGE },
      },
      {
        contentKey: DAY_ONE_MESSAGE_CONTENT_KEY,
        delayMs: 24 * HOUR_MS,
        content: {
          type: 'text',
          text: DAY_ONE_MESSAGE,
          buttons: [[{ text: 'Посмотреть Урок', url: 'https://yogermeisters.com/login?next=%2Fcabinet%2Ffree-lesson' }]],
        },
      },
      {
        contentKey: DAY_ONE_REMINDER_CONTENT_KEY,
        delayMs: 24 * HOUR_MS + 50 * MINUTE_MS,
        content: { type: 'text', text: DAY_ONE_REMINDER_MESSAGE },
      },
      {
        contentKey: DAY_TWO_MESSAGE_CONTENT_KEY,
        delayMs: 48 * HOUR_MS,
        content: {
          type: 'text',
          text: DAY_TWO_MESSAGE,
          buttons: [
            [{ text: '🧘 The Yoga Method', url: 'https://yogermeisters.com/the-yoga-method' }],
            [{ text: '🌿 Чиралы', url: 'https://yogermeisters.com/retreats/cirali-yoga-tour' }],
          ],
        },
      },
    ],
  };
}
